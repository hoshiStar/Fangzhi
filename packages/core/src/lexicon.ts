/** 扩展名归一化。数据里 PDF 与 pdf 并存（4381 + 23）。 */
export function normalizeExt(name: string): string {
  const m = name.match(/\.([a-z0-9]+)$/i);
  return m?.[1]?.toLowerCase() ?? '';
}

